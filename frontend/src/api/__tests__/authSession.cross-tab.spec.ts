import { expect, it, vi } from 'vitest'

it('invalidates the old document and aborts requests on a peer login, while peer rotation stays usable', async () => {
  localStorage.clear()
  const first = await import('../authSession')
  first.replaceAuthSession({ accessToken: 'SYNTHETIC-A', refreshToken: 'SYNTHETIC-A-refresh', user: { id: 101 } })
  const initial = first.captureRequestAuthSession()
  const abort = vi.fn()
  const stop = first.trackAuthRequest(initial, abort)
  vi.resetModules()
  const peer = await import('../authSession')
  peer.commitAuthTokenRotation(peer.captureAuthSession(), { access_token: 'SYNTHETIC-A2', refresh_token: 'SYNTHETIC-A2-refresh', expires_in: 3600 })
  window.dispatchEvent(new StorageEvent('storage', { key: first.AUTH_SESSION_KEY }))
  expect(first.authDocumentIsStale()).toBe(false)
  expect(first.captureRequestAuthSession()).toEqual(initial)
  expect(abort).not.toHaveBeenCalled()
  const replaced = vi.fn()
  window.addEventListener(first.AUTH_SESSION_REPLACED_EVENT, replaced)
  peer.replaceAuthSession({ accessToken: 'SYNTHETIC-B', refreshToken: 'SYNTHETIC-B-refresh', user: { id: 202 } })
  // Real tabs have separate EventTargets; discard the peer document's local event.
  replaced.mockClear()
  window.dispatchEvent(new StorageEvent('storage', { key: first.AUTH_SESSION_KEY }))
  expect(first.authDocumentIsStale()).toBe(true)
  expect(abort).toHaveBeenCalledTimes(1)
  expect(replaced).toHaveBeenCalledTimes(1)
  expect(() => first.captureRequestAuthSession()).toThrow()
  window.removeEventListener(first.AUTH_SESSION_REPLACED_EVENT, replaced)
  stop()
})
