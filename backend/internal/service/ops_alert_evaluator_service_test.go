func TestComputeGroupAvailableRatio(t *testing.T) {
	t.Parallel()

	t.Run("正常情况: 10个账号, 8个可用 = 80%", func(t *testing.T) {
		t.Parallel()

		got := computeGroupAvailableRatio(&GroupAvailability{
			TotalAccounts:  10,
			AvailableCount: 8,
		})
		require.InDelta(t, 80.0, got, 0.0001)
	})

	t.Run("边界情况: TotalAccounts = 0 应返回 0", func(t *testing.T) {
		t.Parallel()

		got := computeGroupAvailableRatio(&GroupAvailability{
			TotalAccounts:  0,
			AvailableCount: 8,
		})
		require.Equal(t, 0.0, got)
	})

	t.Run("边界情况: AvailableCount = 0 应返回 0%", func(t *testing.T) {
		t.Parallel()

		got := computeGroupAvailableRatio(&GroupAvailability{
			TotalAccounts:  10,
			AvailableCount: 0,
		})
		require.Equal(t, 0.0, got)
	})
}

func TestCountAccountsByCondition(t *testing.T) {
	t.Parallel()

	t.Run("测试限流账号统计: acc.IsRateLimited", func(t *testing.T) {
		t.Parallel()

		accounts := map[int64]*AccountAvailability{
			1: {IsRateLimited: true},
			2: {IsRateLimited: false},
			3: {IsRateLimited: true},
		}

		got := countAccountsByCondition(accounts, func(acc *AccountAvailability) bool {
			return acc.IsRateLimited
		})
		require.Equal(t, int64(2), got)
	})

	t.Run("测试错误账号统计（排除临时不可调度）: acc.HasError && acc.TempUnschedulableUntil == nil", func(t *testing.T) {
		t.Parallel()

		until := time.Now().UTC().Add(5 * time.Minute)
		accounts := map[int64]*AccountAvailability{
			1: {HasError: true},
			2: {HasError: true, TempUnschedulableUntil: &until},
			3: {HasError: false},
		}

		got := countAccountsByCondition(accounts, func(acc *AccountAvailability) bool {
			return acc.HasError && acc.TempUnschedulableUntil == nil
		})
		require.Equal(t, int64(1), got)
	})

	t.Run("边界情况: 空 map 应返回 0", func(t *testing.T) {
		t.Parallel()

		got := countAccountsByCondition(map[int64]*AccountAvailability{}, func(acc *AccountAvailability) bool {
			return acc.IsRateLimited
		})
		require.Equal(t, int64(0), got)
	})
}

// TestComputeRuleMetric_AccountTempUnscheduledCount verifies the new
// account_temp_unscheduled_count metric counts accounts currently in the
// temp-unscheduled window and ignores those whose window has expired or
// were never temp-unscheduled.
func TestComputeRuleMetric_AccountTempUnscheduledCount(t *testing.T) {
	t.Parallel()

	now := time.Now().UTC()
	futureUntil := now.Add(5 * time.Minute)
	pastUntil := now.Add(-1 * time.Minute)

	availability := &OpsAccountAvailability{
		Accounts: map[int64]*AccountAvailability{
			// currently temp-unscheduled (window active)
			1: {TempUnschedulableUntil: &futureUntil},
			2: {TempUnschedulableUntil: &futureUntil},
			// temp-unsched window already expired → should NOT count
			3: {TempUnschedulableUntil: &pastUntil},
			// never temp-unscheduled
			4: {HasError: true},
			5: {IsRateLimited: true},
		},
	}

	opsService := &OpsService{
		getAccountAvailability: func(_ context.Context, _ string, _ *int64) (*OpsAccountAvailability, error) {
			return availability, nil
		},
	}
	svc := &OpsAlertEvaluatorService{
		opsService: opsService,
		opsRepo:    &stubOpsRepo{},
	}

	rule := &OpsAlertRule{MetricType: "account_temp_unscheduled_count"}
	val, ok := svc.computeRuleMetric(context.Background(), rule, nil,
		now.Add(-5*time.Minute), now, "", nil)

	require.True(t, ok)
	require.InDelta(t, 2.0, val, 0.0001, "only 2 accounts have an active temp-unsched window")
}

func TestComputeRuleMetricNewIndicators(t *testing.T) {
	t.Parallel()

	groupID := int64(101)
	platform := "openai"

	availability := &OpsAccountAvailability{
		Group: &GroupAvailability{
			GroupID:        groupID,
			TotalAccounts:  10,
			AvailableCount: 8,
		},
		Accounts: map[int64]*AccountAvailability{
			1: {IsRateLimited: true},
			2: {IsRateLimited: true},
			3: {HasError: true},
			4: {HasError: true, TempUnschedulableUntil: timePtr(time.Now().UTC().Add(2 * time.Minute))},
			5: {HasError: false, IsRateLimited: false},
		},
	}

	opsService := &OpsService{
		getAccountAvailability: func(_ context.Context, _ string, _ *int64) (*OpsAccountAvailability, error) {
			return availability, nil
		},
	}

	svc := &OpsAlertEvaluatorService{
		opsService: opsService,
		opsRepo:    &stubOpsRepo{overview: &OpsDashboardOverview{}},
	}

	start := time.Now().UTC().Add(-5 * time.Minute)
	end := time.Now().UTC()
	ctx := context.Background()

	tests := []struct {
		name       string
		metricType string
		groupID    *int64
		wantValue  float64
		wantOK     bool
	}{
		{
			name:       "group_available_accounts",
			metricType: "group_available_accounts",
			groupID:    &groupID,
			wantValue:  8,
			wantOK:     true,
		},
		{
			name:       "group_available_ratio",
			metricType: "group_available_ratio",
			groupID:    &groupID,
			wantValue:  80.0,
			wantOK:     true,
		},
		{
			name:       "account_rate_limited_count",
			metricType: "account_rate_limited_count",
			groupID:    nil,
			wantValue:  2,
			wantOK:     true,
		},
		{
			name:       "account_error_count",
			metricType: "account_error_count",
			groupID:    nil,
			wantValue:  1,
			wantOK:     true,
		},
		{
			name:       "group_available_accounts without group_id returns false",
			metricType: "group_available_accounts",
			groupID:    nil,
			wantValue:  0,
			wantOK:     false,
		},
		{
			name:       "group_available_ratio without group_id returns false",
			metricType: "group_available_ratio",
			groupID:    nil,
			wantValue:  0,
			wantOK:     false,
		},
	}

	for _, tt := range tests {
		tt := tt
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			rule := &OpsAlertRule{
				MetricType: tt.metricType,
			}
			gotValue, gotOK := svc.computeRuleMetric(ctx, rule, nil, start, end, platform, tt.groupID)
			require.Equal(t, tt.wantOK, gotOK)
			if !tt.wantOK {
				return
			}
			require.InDelta(t, tt.wantValue, gotValue, 0.0001)
		})
	}
}

// v0.1.21: maybeSendAlertEmail 顶部的提前 return 曾经完全静默——没有 SMTP 收件人的
// 网关照旧每 5 分钟创建告警事件，而日志和心跳里都没有「为什么一封都没发」。
// 这两条用例把新行为钉住：跳过必须留原因，且原因要能出现在 job heartbeat 里。
func TestMaybeSendAlertEmailRecordsSkipWhenRuleOptsOut(t *testing.T) {
	svc := &OpsAlertEvaluatorService{
		emailService: &EmailService{},
		opsService:   &OpsService{},
	}
	if got := svc.emailSkipSummary(); got != "" {
		t.Fatalf("summary should be empty before the first skip, got %q", got)
	}

	rule := &OpsAlertRule{ID: 7, Name: "disk pressure", NotifyEmail: false}
	event := &OpsAlertEvent{ID: 42}

	if sent := svc.maybeSendAlertEmail(context.Background(), nil, rule, event); sent {
		t.Fatal("rule with NotifyEmail=false must not send")
	}

	summary := svc.emailSkipSummary()
	if !strings.Contains(summary, "email_skips_total=1") {
		t.Fatalf("summary should count the skip, got %q", summary)
	}
	if !strings.Contains(summary, "rule_notify_disabled") {
		t.Fatalf("summary should carry the reason, got %q", summary)
	}
}

func TestNoteEmailSkipKeepsLatestReason(t *testing.T) {
	svc := &OpsAlertEvaluatorService{}
	svc.noteEmailSkip("no_recipients", &OpsAlertRule{ID: 1}, &OpsAlertEvent{ID: 2})
	svc.noteEmailSkip("notifications_disabled", &OpsAlertRule{ID: 1}, &OpsAlertEvent{ID: 3})

	summary := svc.emailSkipSummary()
	if !strings.Contains(summary, "email_skips_total=2") {
		t.Fatalf("summary should count both skips, got %q", summary)
	}
	if !strings.Contains(summary, "notifications_disabled") {
		t.Fatalf("summary should carry the latest reason, got %q", summary)
	}
}

func TestOpsAlertEmailVariablesCarryResolvedContext(t *testing.T) {
	firedAt := time.Date(2026, 11, 16, 8, 0, 0, 0, time.UTC)
	resolvedAt := firedAt.Add(5 * time.Minute)
	rule := &OpsAlertRule{Name: "上游流式错误", Severity: "P1", MetricType: "upstream_error_rate", Operator: ">=", Threshold: 5}
	event := &OpsAlertEvent{
		ID:          42,
		Status:      OpsAlertStatusResolved,
		MetricValue: float64Ptr(7.5),
		FiredAt:     firedAt,
		ResolvedAt:  &resolvedAt,
	}

	variables := opsAlertEmailVariables(rule, event, "https://zhijing.example/admin/ops")
	require.Equal(t, "已恢复", variables["alert_status_label"])
	require.Equal(t, resolvedAt.Format(time.RFC3339), variables["resolved_at"])
	require.Equal(t, "https://zhijing.example/admin/ops", variables["dashboard_url"])
	require.Equal(t, "7.50", variables["metric_value"])

	body := buildOpsAlertEmailBody(rule, event)
	require.Contains(t, body, "已恢复")
	require.Contains(t, body, "恢复时间")
	require.Contains(t, body, resolvedAt.Format(time.RFC3339))
}
